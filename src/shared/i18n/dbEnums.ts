export type DbEnumName = keyof typeof dbEnumLabels.vi;
export function labelDbEnum(locale: "vi" | "en", name: DbEnumName, value: string | null | undefined): string {
  if (!value) return "";
  const labels = dbEnumLabels[locale][name] as Record<string, string>;
  return labels[value] ?? value;
}

import { useLocaleStore } from "./store";
export function useDbEnumLabel() {
  const locale = useLocaleStore((state) => state.locale);
  return (name: DbEnumName, value: string | null | undefined) => labelDbEnum(locale, name, value);
}
