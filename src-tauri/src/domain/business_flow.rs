//! Pure Business Flow domain types, provenance tracking, and structural validation (`REQ-DOM-001`, `REQ-DOM-002`).
//!
//! This module is 100% pure Rust (`serde`, `serde_json`, `std::collections`) with zero dependency
//! on `rusqlite`, `tokio::fs`, `reqwest`, or `tauri`.
//!
//! Models the authoritative canonical structure of `BusinessFlowData` stored in `draft_versions.data_json`:
//! - `meta`: `{ version, phase, subphase, updated_at }`
//! - `require`: `{ project, character[] }`
//! - `optional`: `{ overview_phase, chapter_phase, world_building_phase, scene_config_phase, character_appearance_phase, character_psychological_phase, character_life_experience_phase, relationship_phase }`
//! - `user_constraints`: ordered list of free-form user constraints
//! - `decision_log`: ordered list of explicit planning decisions
//! - `_counters`: monotone per-parent counters (`BTreeMap<String, u64>`) for stable entity `code` allocation

use serde::{Deserialize, Serialize};
use serde_json::Value;
