/// Metadata header of `BusinessFlowData` (`be-core.md` §4.1).
///
/// Note: `meta.updated_at` is excluded from RFC 8785 JCS `canonical_state` and `state_data_hash`.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct DraftMeta {
    pub version: String,
    pub phase: i32,
    #[serde(default)]
    pub subphase: Option<i32>,
    #[serde(default)]
    pub updated_at: Option<String>,
}

impl Default for DraftMeta {
    fn default() -> Self {
        Self {
            version: "1.0".to_string(),
            phase: 0,
            subphase: None,
            updated_at: None,
        }
    }
}

impl DraftMeta {
    /// Validates `phase` and `subphase` according to `core.md` §3.6 and `be-core.md` §4.5:
    /// `phase` must be in `0..=6`; `subphase` is `Some(1 | 2 | 3)` only when `phase == 5`, and `None` otherwise.
    pub fn validate(&self) -> Result<(), DomainError> {
        if self.version.trim().is_empty() {
            return Err(DomainError::UnknownStateShape {
                reason: "meta.version must not be empty".to_string(),
            });
        }
        if !(0..=6).contains(&self.phase) {
            return Err(DomainError::InvalidPhaseSubphase {
                phase: self.phase,
                subphase: self.subphase,
            });
        }
        match (self.phase, self.subphase) {
            (5, Some(1..=3)) | (5, None) => Ok(()),
            (5, Some(_)) => Err(DomainError::InvalidPhaseSubphase {
                phase: self.phase,
                subphase: self.subphase,
            }),
            (_, None) => Ok(()),
            (_, Some(_)) => Err(DomainError::InvalidPhaseSubphase {
                phase: self.phase,
                subphase: self.subphase,
            }),
        }
    }
}

