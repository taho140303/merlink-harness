use thiserror::Error;

/// Provenance source tag attached to every field or element in `BusinessFlowData` (`core.md` §1.3, `be-core.md` §4.1).
///
/// Supports both canonical SSOT `"ai_generated"` and alias `"ai"`, plus `"user"`, `"user_edited"`,
/// `"system"`, and `"incomplete"` (used when normalizing missing/null `TrackedField<T>` values per `be-core.md` §6.4.2).
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
#[derive(Default)]
pub enum ProvenanceSource {
    /// Provided directly by the user (`"user"`). Protected from direct AI overwrite or deletion.
    User,
    /// Originally AI-generated or user-created, then edited or confirmed by the user (`"user_edited"`).
    /// Protected from direct AI overwrite or deletion.
    UserEdited,
    /// Generated by AI (`"ai_generated"`, also accepts `"ai"` on deserialization).
    /// AI may overwrite freely unless protected descendants exist.
    #[serde(alias = "ai")]
    AiGenerated,
    /// System-populated default or structural metadata (`"system"`).
    System,
    /// Normalized sentinel for an unset / `null` field (`"incomplete"`, `be-core.md` §6.4.2).
    #[default]
    Incomplete,
}

impl ProvenanceSource {
    /// Alias constant for `ProvenanceSource::AiGenerated` so callers using `ProvenanceSource::Ai`
    /// or `ProvenanceSource::AiGenerated` interoperate seamlessly.
    #[allow(non_upper_case_globals)]
    pub const Ai: ProvenanceSource = ProvenanceSource::AiGenerated;

    /// Returns `true` if this provenance source is protected from direct AI overwrite or deletion
    /// (`user` or `user_edited` per `core.md` §1.3).
    pub const fn is_protected_from_ai_overwrite(self) -> bool {
        matches!(self, ProvenanceSource::User | ProvenanceSource::UserEdited)
    }

    /// Returns `true` if this source counts toward the "Confirmed" (`Đã xác nhận`) progress bar
    /// (`user` or `user_edited` per `core.md` §3.1.3).
    pub const fn is_confirmed(self) -> bool {
        matches!(self, ProvenanceSource::User | ProvenanceSource::UserEdited)
    }

    /// Returns `true` if this source counts toward the "AI Suggested" (`AI đề xuất`) progress bar
    /// (`ai_generated` per `core.md` §3.1.3).
    pub const fn is_ai_suggested(self) -> bool {
        matches!(self, ProvenanceSource::AiGenerated)
    }

    /// Returns the canonical snake_case string representation used in JCS normalization.
    pub const fn as_str(self) -> &'static str {
        match self {
            ProvenanceSource::User => "user",
            ProvenanceSource::UserEdited => "user_edited",
            ProvenanceSource::AiGenerated => "ai_generated",
            ProvenanceSource::System => "system",
            ProvenanceSource::Incomplete => "incomplete",
        }
    }
}


/// A nullable domain field paired with its provenance source (`be-core.md` §4.1, §6.4.2).
///
/// During JCS canonicalization (`domain::fingerprint`), any missing or `value: null` `TrackedField<T>`
/// with absent/null source is normalized to `{"value": null, "source": "incomplete"}` so omitted
/// optional fields and explicit null fields produce identical canonical bytes.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct TrackedField<T> {
    #[serde(default)]
    pub value: Option<T>,
    #[serde(default)]
    pub source: Option<ProvenanceSource>,
}

impl<T> Default for TrackedField<T> {
    fn default() -> Self {
        Self {
            value: None,
            source: None,
        }
    }
}

impl<T> TrackedField<T> {
    /// Creates an empty (`null`) tracked field.
    pub const fn unset() -> Self {
        Self {
            value: None,
            source: None,
        }
    }

    /// Creates a populated tracked field with an explicit provenance source.
    pub const fn new(value: T, source: ProvenanceSource) -> Self {
        Self {
            value: Some(value),
            source: Some(source),
        }
    }

    /// Creates a user-sourced tracked field.
    pub const fn user(value: T) -> Self {
        Self::new(value, ProvenanceSource::User)
    }

    /// Creates an AI-generated tracked field.
    pub const fn ai(value: T) -> Self {
        Self::new(value, ProvenanceSource::AiGenerated)
    }

    /// Creates a user-edited tracked field.
    pub const fn user_edited(value: T) -> Self {
        Self::new(value, ProvenanceSource::UserEdited)
    }

    /// Returns the effective provenance source (`Incomplete` when `value` is `None` and `source` is `None`).
    pub fn effective_source(&self) -> ProvenanceSource {
        match (&self.value, self.source) {
            (None, None) => ProvenanceSource::Incomplete,
            (_, Some(src)) => src,
            (Some(_), None) => ProvenanceSource::Incomplete,
        }
    }

    /// Returns `true` if this field currently holds a `Some` value and its source is `User` or `UserEdited`.
    pub fn is_protected_from_ai_overwrite(&self) -> bool {
        self.value.is_some()
            && self
                .source
                .map(|s| s.is_protected_from_ai_overwrite())
                .unwrap_or(false)
    }
}

/// Pure domain validation and canonicalization errors (`P2S2-N`, `P2S2-C`, `phase2_sprint2_deep1-F1`, `phase2_sprint2_deep1-F2`).
#[derive(Debug, Clone, PartialEq, Eq, Error)]
pub enum DomainError {
    #[error("P2S2-N: unknown or malformed BusinessFlowData state shape: {reason}")]
    UnknownStateShape { reason: String },

    #[error("P2S2-N: invalid phase/subphase combination (phase={phase}, subphase={subphase:?})")]
    InvalidPhaseSubphase { phase: i32, subphase: Option<i32> },

    #[error("P2S2-C: entity code collision detected for code '{code}'")]
    CodeCollision { code: String },

    #[error("P2S2-C: monotone counter rewind or invalid counter state for key '{counter_key}' (current={current}, proposed={proposed})")]
    CounterRewind {
        counter_key: String,
        current: u64,
        proposed: u64,
    },

    #[error("P2S2-C: invalid parent or entity code '{code}': {reason}")]
    InvalidEntityCode { code: String, reason: String },

    #[error("P2S2-N: non-finite floating point number in canonical JSON at '{path}'")]
    NonFiniteNumber { path: String },

    #[error("CONTRACT_BLOCKED: {reason}")]
    ContractBlocked { reason: String },
}

