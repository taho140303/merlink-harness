pub type EntityCounters = BTreeMap<String, u64>;

/// Canonical root structure stored in `draft_versions.data_json` and held in memory inside `WorkingState`
/// (`core.md` §1.2, §3.6; `be-core.md` §4.1).
#[derive(Debug, Clone, Default, PartialEq, Eq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct BusinessFlowData {
    pub meta: DraftMeta,
    #[serde(default)]
    pub require: RequireSection,
    #[serde(default)]
    pub optional: OptionalSection,
    #[serde(default)]
    pub user_constraints: Vec<UserConstraintEntry>,
    #[serde(default)]
    pub decision_log: Vec<DecisionLogEntry>,
    #[serde(default, rename = "_counters")]
    pub counters: EntityCounters,
}

impl BusinessFlowData {
    /// Creates a fresh empty `BusinessFlowData` at Phase 0.
    pub fn new() -> Self {
        Self::default()
    }

    /// Parses and validates a raw JSON string into `BusinessFlowData`, rejecting unknown top-level
    /// or nested keys, legacy misspelled keys (such as `charactar_psychological_phase` or embedded
    /// `pending_patches`), and invalid `phase`/`subphase` combinations (`phase2_sprint2_deep1-F1`).
    pub fn from_json_str_strict(raw_json: &str) -> Result<Self, DomainError> {
        let value: Value =
            serde_json::from_str(raw_json).map_err(|err| DomainError::UnknownStateShape {
                reason: format!("invalid JSON syntax: {err}"),
            })?;
        Self::from_json_value_strict(&value)
    }

    /// Parses and validates a `serde_json::Value` into `BusinessFlowData` without mutating any caller state.
    pub fn from_json_value_strict(value: &Value) -> Result<Self, DomainError> {
        let obj = value
            .as_object()
            .ok_or_else(|| DomainError::UnknownStateShape {
                reason: "root BusinessFlowData value must be a JSON object".to_string(),
            })?;

        if !obj.contains_key("meta") {
            return Err(DomainError::UnknownStateShape {
                reason: "missing required top-level key 'meta'".to_string(),
            });
        }

        let state: Self = serde_json::from_value(value.clone()).map_err(|err| {
            DomainError::UnknownStateShape {
                reason: err.to_string(),
            }
        })?;
        state.validate_structure()?;
        Ok(state)
    }

    /// Validates structural invariants of `BusinessFlowData`:
    /// - `meta` phase/subphase rules
    /// - non-empty and globally unique entity `code`s across the draft (`core.md` §3.8)
    pub fn validate_structure(&self) -> Result<(), DomainError> {
        self.meta.validate()?;
        let _ = self.collect_unique_entity_codes()?;
        Ok(())
    }

    /// Collects all entity `code`s currently present in `BusinessFlowData`, returning
    /// `Err(DomainError::CodeCollision)` if any duplicate `code` exists or `Err(DomainError::InvalidEntityCode)`
    /// if any required entity `code` is empty.
    pub fn collect_unique_entity_codes(&self) -> Result<BTreeSet<String>, DomainError> {
        let mut codes = BTreeSet::new();

        let mut insert_code = |code: &str, kind: &str| -> Result<(), DomainError> {
            let trimmed = code.trim();
            if trimmed.is_empty() {
                return Err(DomainError::InvalidEntityCode {
                    code: code.to_string(),
                    reason: format!("{kind} code must not be empty"),
                });
            }
            if !codes.insert(trimmed.to_string()) {
                return Err(DomainError::CodeCollision {
                    code: trimmed.to_string(),
                });
            }
            Ok(())
        };

        if let Some(proj_code) = &self.require.project.code {
            insert_code(proj_code, "project")?;
        }

        for ch in &self.require.character {
            insert_code(&ch.code, "require.character")?;
        }

        for arc in &self.optional.overview_phase.arcs {
            insert_code(&arc.code, "overview_phase.arc")?;
            for eb in &arc.motif.event_blocks {
                insert_code(&eb.code, "arc.event_block")?;
            }
            if let Some(theme_code) = &arc.themes.code {
                insert_code(theme_code, "arc.theme")?;
            }
        }

        for ch_arc in &self.optional.chapter_phase.arcs {
            // Note: ch_arc.code references the arc in overview_phase, so only check non-empty
            if ch_arc.code.trim().is_empty() {
                return Err(DomainError::InvalidEntityCode {
                    code: ch_arc.code.clone(),
                    reason: "chapter_phase.arc.code must not be empty".to_string(),
                });
            }
            for chapter in &ch_arc.chapters {
                insert_code(&chapter.code, "chapter")?;
                for scene in &chapter.scenes {
                    insert_code(&scene.code, "scene")?;
                }
            }
        }

        for ws in &self.optional.world_building_phase.world_settings {
            insert_code(&ws.code, "world_setting")?;
            for lore in &ws.lore_entries {
                insert_code(&lore.code, "lore_entry")?;
            }
        }

        for life_char in &self.optional.character_life_experience_phase.character {
            for comp in &life_char.competences {
                insert_code(&comp.code, "character_competence")?;
            }
        }

        for rel in &self.optional.relationship_phase.relationship {
            insert_code(&rel.code, "relationship")?;
        }

        Ok(codes)
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn provenance_source_protection_and_serde_aliases() {
        assert!(ProvenanceSource::User.is_protected_from_ai_overwrite());
        assert!(ProvenanceSource::UserEdited.is_protected_from_ai_overwrite());
        assert!(!ProvenanceSource::AiGenerated.is_protected_from_ai_overwrite());
        assert!(!ProvenanceSource::Ai.is_protected_from_ai_overwrite());
        assert!(!ProvenanceSource::System.is_protected_from_ai_overwrite());
        assert!(!ProvenanceSource::Incomplete.is_protected_from_ai_overwrite());

        let from_ai_generated: ProvenanceSource = serde_json::from_str("\"ai_generated\"").unwrap();
        let from_ai_alias: ProvenanceSource = serde_json::from_str("\"ai\"").unwrap();
        assert_eq!(from_ai_generated, ProvenanceSource::AiGenerated);
        assert_eq!(from_ai_alias, ProvenanceSource::AiGenerated);
        assert_eq!(
            serde_json::to_string(&ProvenanceSource::AiGenerated).unwrap(),
            "\"ai_generated\""
        );
    }

    #[test]
    fn strict_deserialization_rejects_unknown_fields_and_invalid_subphase() {
        let bad_json = r#"{
            "meta": { "version": "1.0", "phase": 2, "subphase": 1 },
            "require": {}
        }"#;
        let err = BusinessFlowData::from_json_str_strict(bad_json).unwrap_err();
        assert!(matches!(
            err,
            DomainError::InvalidPhaseSubphase {
                phase: 2,
                subphase: Some(1)
            }
        ));

        let unknown_key_json = r#"{
            "meta": { "version": "1.0", "phase": 0 },
            "pending_patches": []
        }"#;
        let err2 = BusinessFlowData::from_json_str_strict(unknown_key_json).unwrap_err();
        assert!(matches!(err2, DomainError::UnknownStateShape { .. }));
    }
}
